/// Raw image memory kept for copy-back; older unpinned images are dropped beyond this.
const IMAGE_BUDGET: usize = 64 * 1024 * 1024;
/// Larger texts are not recorded (keeps memory bounded, avoids giant log dumps).
const MAX_TEXT: usize = 1024 * 1024;
const PREVIEW_CHARS: usize = 300;

/// Pasteboard types password managers set to say "don't record this".
/// nspasteboard.org markers (macOS), Windows clipboard-history opt-outs, KDE/KeePassXC hint.
const SECRET_MARKERS: &[&str] = &[
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "ExcludeClipboardContentFromMonitorProcessing",
    "CanIncludeInClipboardHistory",
    "x-kde-passwordManagerHint",
];

pub fn is_secret(formats: &[String]) -> bool {
    formats.iter().any(|f| SECRET_MARKERS.contains(&f.as_str()))
}

// ---------- pure history ----------

#[derive(Debug)]
pub enum Content<I> {
    Text(String),
    /// Payload + raw size in bytes.
    Image(I, usize),
}

#[derive(Debug)]
pub struct Entry<I> {
    pub id: u64,
    pub pinned: bool,
    pub content: Content<I>,
}

#[derive(Debug, Serialize, Deserialize, PartialEq)]
pub struct Saved {
    pub text: String,
    pub pinned: bool,
}

#[derive(Debug)]
pub struct History<I> {
    /// Newest first.
    pub entries: Vec<Entry<I>>,
    next_id: u64,
    pub max: usize,
}

impl<I> History<I> {
    pub fn new(max: usize) -> Self {
        Self {
            entries: vec![],
            next_id: 1,
            max,
        }
    }

    fn insert(&mut self, pinned: bool, content: Content<I>) {
        self.entries.insert(
            0,
            Entry {
                id: self.next_id,
                pinned,
                content,
            },
        );
        self.next_id += 1;
        self.trim();
    }

    /// Returns false if nothing changed (empty, too large, or already newest).
    pub fn push_text(&mut self, text: String) -> bool {
        if text.trim().is_empty() || text.len() > MAX_TEXT {
            return false;
        }
        let pos = self
            .entries
            .iter()
            .position(|e| matches!(&e.content, Content::Text(t) if *t == text));
        match pos {
            Some(0) => false,
            // Copied again: move it to the top, keep its pin.
            Some(i) => {
                let e = self.entries.remove(i);
                self.entries.insert(0, e);
                true
            }
            None => {
                self.insert(false, Content::Text(text));
                true
            }
        }
    }

    pub fn push_image(&mut self, img: I, bytes: usize) {
        self.insert(false, Content::Image(img, bytes));
    }

    /// Drop unpinned entries beyond `max`, then the oldest unpinned images over budget.
    pub fn trim(&mut self) {
        let mut unpinned = 0;
        let max = self.max;
        self.entries.retain(|e| {
            if e.pinned {
                return true;
            }
            unpinned += 1;
            unpinned <= max
        });
        let mut total: usize = self.image_bytes();
        while total > IMAGE_BUDGET {
            let Some(i) = self
                .entries
                .iter()
                .rposition(|e| !e.pinned && matches!(e.content, Content::Image(..)))
            else {
                break;
            };
            if let Content::Image(_, b) = self.entries.remove(i).content {
                total -= b;
            }
        }
    }

    fn image_bytes(&self) -> usize {
        self.entries
            .iter()
            .map(|e| match e.content {
                Content::Image(_, b) => b,
                Content::Text(_) => 0,
            })
            .sum()
    }

    pub fn get(&self, id: u64) -> Option<&Entry<I>> {
        self.entries.iter().find(|e| e.id == id)
    }

    pub fn toggle_pin(&mut self, id: u64) {
        if let Some(e) = self.entries.iter_mut().find(|e| e.id == id) {
            e.pinned = !e.pinned;
        }
        self.trim();
    }

    pub fn remove(&mut self, id: u64) {
        self.entries.retain(|e| e.id != id);
    }

    /// Clears everything except pins.
    pub fn clear(&mut self) {
        self.entries.retain(|e| e.pinned);
    }

    pub fn saved(&self) -> Vec<Saved> {
        self.entries
            .iter()
            .filter_map(|e| match &e.content {
                Content::Text(t) => Some(Saved {
                    text: t.clone(),
                    pinned: e.pinned,
                }),
                Content::Image(..) => None,
            })
            .collect()
    }

    pub fn load(&mut self, saved: Vec<Saved>) {
        // Oldest first so the newest ends up on top.
        for s in saved.into_iter().rev() {
            if !self
                .entries
                .iter()
                .any(|e| matches!(&e.content, Content::Text(t) if *t == s.text))
            {
                self.insert(s.pinned, Content::Text(s.text));
            }
        }
    }

    /// Pinned first, then newest; text filtered case-insensitively (images only match "").
    pub fn view(&self, query: &str) -> Vec<&Entry<I>> {
        let q = query.to_lowercase();
        let mut v: Vec<_> = self
            .entries
            .iter()
            .filter(|e| match &e.content {
                Content::Text(t) => q.is_empty() || t.to_lowercase().contains(&q),
                Content::Image(..) => q.is_empty(),
            })
            .collect();
        v.sort_by_key(|e| !e.pinned); // stable: keeps newest-first inside each group
        v
    }
}

// ---------- OS glue ----------

struct Img {
    data: RustImageData,
    thumb: slint::Image,
    size: (u32, u32),
}

thread_local! {
    static INSTANCE: RefCell<Weak<ClipboardModule>> = RefCell::default();
}

/// Runs on the watcher thread; hops to the UI thread to read the clipboard.
struct OnChange;

impl ClipboardHandler for OnChange {
    fn on_clipboard_change(&mut self) {
        let _ = slint::invoke_from_event_loop(|| {
            if let Some(m) = INSTANCE.with(|i| i.borrow().upgrade()) {
                m.capture();
            }
        });
    }
}

pub struct ClipboardModule {
    me: Weak<ClipboardModule>,
    ctx: Ctx,
    history: RefCell<History<Img>>,
    os: RefCell<Option<ClipboardContext>>,
    watcher: RefCell<Option<WatcherShutdown>>,
    cfg: RefCell<config::Clipboard>,
    enabled: Cell<bool>,
    query: RefCell<String>,
    windows: RefCell<Vec<slint::Weak<NotchWindow>>>,
}

fn store_path() -> Option<PathBuf> {
    directories::ProjectDirs::from("", "", "notch-utils")
        .map(|d| d.data_dir().join("clipboard.json"))
}

impl ClipboardModule {
    pub fn new(ctx: Ctx) -> Rc<Self> {
        let m = Rc::new_cyclic(|me| Self {
            me: me.clone(),
            ctx,
            history: RefCell::new(History::new(50)),
            os: RefCell::default(),
            watcher: RefCell::default(),
            cfg: RefCell::default(),
            enabled: Cell::new(false),
            query: RefCell::default(),
            windows: RefCell::default(),
        });
        INSTANCE.with(|i| *i.borrow_mut() = Rc::downgrade(&m));
        m
    }

    fn start(&self) {
        if self.watcher.borrow().is_some() {
            return;
        }
        let mut w = match ClipboardWatcherContext::new() {
            Ok(w) => w,
            Err(e) => return log::warn!("clipboard watcher unavailable: {e}"),
        };
        w.add_handler(OnChange);
        *self.watcher.borrow_mut() = Some(w.get_shutdown_channel());
        let spawned = std::thread::Builder::new()
            .name("clipboard".into())
            .spawn(move || w.start_watch());
        if let Err(e) = spawned {
            log::warn!("clipboard watcher thread: {e}");
            *self.watcher.borrow_mut() = None;
        }
    }

    /// Stop collecting and forget everything (privacy: disabled means disabled).
    fn stop(&self) {
        self.watcher.borrow_mut().take(); // dropping the channel stops the thread
        *self.os.borrow_mut() = None;
        self.history.borrow_mut().entries.clear();
        self.sync();
    }

    fn with_os<T>(&self, f: impl FnOnce(&ClipboardContext) -> T) -> Option<T> {
        let mut os = self.os.borrow_mut();
        if os.is_none() {
            *os = ClipboardContext::new()
                .map_err(|e| log::warn!("clipboard: {e}"))
                .ok();
        }
        os.as_ref().map(f)
    }

    fn capture(&self) {
        if !self.enabled.get() {
            return;
        }
        let read = self.with_os(|c| {
            if is_secret(&c.available_formats().unwrap_or_default()) {
                log::debug!("clipboard: skipped secret");
                return None;
            }
            if c.has(ContentFormat::Text) {
                c.get_text().ok().map(Content::Text)
            } else if c.has(ContentFormat::Image) {
                c.get_image().ok().and_then(make_img).map(|i| {
                    let bytes = i.size.0 as usize * i.size.1 as usize * 4;
                    Content::Image(i, bytes)
                })
            } else {
                None
            }
        });
        let changed = match read.flatten() {
            Some(Content::Text(t)) => self.history.borrow_mut().push_text(t),
            Some(Content::Image(i, b)) => {
                self.history.borrow_mut().push_image(i, b);
                true
            }
            None => false,
        };
        if changed {
            self.save();
            self.sync();
        }
    }

    fn copy(&self, id: u64) {
        let h = self.history.borrow();
        let Some(e) = h.get(id) else { return };
        let r = self.with_os(|c| match &e.content {
            Content::Text(t) => c.set_text(t.clone()),
            Content::Image(img, _) => match img.data.get_dynamic_image() {
                Ok(d) => c.set_image(RustImageData::from_dynamic_image(d)),
                Err(e) => Err(e),
            },
        });
        drop(h);
        match r {
            Some(Err(e)) => log::warn!("clipboard: copy failed: {e}"),
            // Done: get out of the way so the user can paste.
            Some(Ok(())) => (self.ctx.collapse)(),
            None => {}
        }
    }

    fn save(&self) {
        let Some(path) = store_path() else { return };
        if !self.cfg.borrow().persist {
            return;
        }
        let saved = self.history.borrow().saved();
        if let Err(e) = write_private(&path, &serde_json::to_vec(&saved).unwrap_or_default()) {
            log::warn!("clipboard: saving history: {e}");
        }
    }

    fn sync(&self) {
        let h = self.history.borrow();
        let rows: Vec<ClipEntry> = h
            .view(&self.query.borrow())
            .into_iter()
            .map(|e| match &e.content {
                Content::Text(t) => ClipEntry {
                    id: e.id as i32,
                    pinned: e.pinned,
                    text: preview(t).into(),
                    meta: meta_text(t).into(),
                    ..Default::default()
                },
                Content::Image(i, _) => ClipEntry {
                    id: e.id as i32,
                    pinned: e.pinned,
                    is_image: true,
                    image: i.thumb.clone(),
                    meta: format!("{} × {}", i.size.0, i.size.1).into(),
                    ..Default::default()
                },
            })
            .collect();
        let total = h.entries.len() as i32;
        drop(h);
        self.windows.borrow_mut().retain(|w| {
            let Some(ui) = w.upgrade() else { return false };
            let g = ui.global::<ClipState>();
            g.set_entries(Rc::new(VecModel::from(rows.clone())).into());
            g.set_total(total);
            g.set_enabled(self.enabled.get());
            true
        });
    }
}

fn make_img(data: RustImageData) -> Option<Img> {
    let size = data.get_size();
    let thumb = data.thumbnail(360, 120).ok()?.to_rgba8().ok()?;
    let buf = SharedPixelBuffer::<slint::Rgba8Pixel>::clone_from_slice(
        thumb.as_raw(),
        thumb.width(),
        thumb.height(),
    );
    Some(Img {
        data,
        thumb: slint::Image::from_rgba8(buf),
        size,
    })
}

fn preview(t: &str) -> String {
    let one_line: String = t.split_whitespace().collect::<Vec<_>>().join(" ");
    match one_line.char_indices().nth(PREVIEW_CHARS) {
        Some((i, _)) => format!("{}…", &one_line[..i]),
        None => one_line,
    }
}

fn meta_text(t: &str) -> String {
    let lines = t.lines().count();
    if lines > 1 {
        format!("{lines} lines")
    } else {
        String::new()
    }
}

/// Atomic write, readable by the current user only.
fn write_private(path: &std::path::Path, data: &[u8]) -> std::io::Result<()> {
    use std::io::Write;
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir)?;
    }
    let tmp = path.with_extension("json.tmp");
    let mut opts = std::fs::OpenOptions::new();
    opts.write(true).create(true).truncate(true);
    #[cfg(unix)]
    std::os::unix::fs::OpenOptionsExt::mode(&mut opts, 0o600);
    opts.open(&tmp)?.write_all(data)?;
    std::fs::rename(tmp, path)
}

impl Module for ClipboardModule {
    fn id(&self) -> &'static str {
        "clipboard"
    }

    fn title(&self) -> &'static str {
        "Clipboard"
    }

    fn attach(&self, ui: &NotchWindow) {
        let g = ui.global::<ClipState>();
        let me = self.me.clone();
        g.on_copy(move |id| {
            if let Some(m) = me.upgrade() {
                m.copy(id as u64)
            }
        });
        let me = self.me.clone();
        g.on_toggle_pin(move |id| {
            if let Some(m) = me.upgrade() {
                m.history.borrow_mut().toggle_pin(id as u64);
                m.save();
                m.sync();
            }
        });
        let me = self.me.clone();
        g.on_remove(move |id| {
            if let Some(m) = me.upgrade() {
                m.history.borrow_mut().remove(id as u64);
                m.save();
                m.sync();
            }
        });
        let me = self.me.clone();
        g.on_clear(move || {
            if let Some(m) = me.upgrade() {
                m.history.borrow_mut().clear();
                m.save();
                m.sync();
            }
        });
        let me = self.me.clone();
        g.on_search(move |q| {
            if let Some(m) = me.upgrade() {
                *m.query.borrow_mut() = q.to_string();
                m.sync();
            }
        });
        self.windows.borrow_mut().push(ui.as_weak());
        self.sync();
    }

    fn config_changed(&self, cfg: &Config) {
        let new = cfg.modules.clipboard.clone();
        let was_persist = self.cfg.borrow().persist;
        let first = !self.enabled.get() && self.history.borrow().entries.is_empty();
        self.history.borrow_mut().max = new.max_entries.max(1);
        self.history.borrow_mut().trim();
        *self.cfg.borrow_mut() = new.clone();

        let enabled = cfg.layout.modules.iter().any(|m| m == "clipboard");
        match (self.enabled.replace(enabled), enabled) {
            (false, true) => {
                if new.persist && first {
                    self.load();
                }
                self.start();
            }
            (true, false) => self.stop(),
            _ => {}
        }
        match (was_persist, new.persist) {
            // Turned off: remove what was saved.
            (true, false) => {
                if let Some(p) = store_path() {
                    let _ = std::fs::remove_file(p);
                }
            }
            (false, true) => self.save(),
            _ => {}
        }
        self.sync();
    }
}

impl ClipboardModule {
    fn load(&self) {
        let Some(path) = store_path() else { return };
        match std::fs::read(&path) {
            Ok(b) => match serde_json::from_slice::<Vec<Saved>>(&b) {
                Ok(saved) => self.history.borrow_mut().load(saved),
                Err(e) => log::warn!("clipboard: {}: {e}", path.display()),
            },
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => {}
            Err(e) => log::warn!("clipboard: {}: {e}", path.display()),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn texts(h: &History<()>) -> Vec<&str> {
        h.entries
            .iter()
            .map(|e| match &e.content {
                Content::Text(t) => t.as_str(),
                Content::Image(..) => "<img>",
            })
            .collect()
    }

    #[test]
    fn push_dedupes_and_moves_to_top() {
        let mut h = History::<()>::new(10);
        assert!(h.push_text("a".into()));
        assert!(h.push_text("b".into()));
        assert!(!h.push_text("b".into()), "already newest");
        assert!(h.push_text("a".into()));
        assert_eq!(texts(&h), ["a", "b"]);
        assert!(!h.push_text("   ".into()));
    }

    #[test]
    fn trim_keeps_pins_outside_the_limit() {
        let mut h = History::<()>::new(2);
        h.push_text("old".into());
        let old = h.entries[0].id;
        h.toggle_pin(old);
        for t in ["x", "y", "z"] {
            h.push_text(t.into());
        }
        assert_eq!(texts(&h), ["z", "y", "old"]);
    }

    #[test]
    fn image_budget_drops_oldest_unpinned_image() {
        let mut h = History::<()>::new(50);
        h.push_image((), IMAGE_BUDGET / 2);
        h.toggle_pin(h.entries[0].id);
        h.push_image((), IMAGE_BUDGET / 2);
        h.push_text("t".into());
        h.push_image((), IMAGE_BUDGET / 2);
        assert_eq!(texts(&h), ["<img>", "t", "<img>"]);
        assert!(h.entries[2].pinned, "pinned image survives");
    }

    #[test]
    fn clear_keeps_pins_and_view_sorts_pins_first() {
        let mut h = History::<()>::new(10);
        h.push_text("pin me".into());
        h.toggle_pin(h.entries[0].id);
        h.push_text("Hello World".into());
        let view: Vec<_> = h.view("").iter().map(|e| e.id).collect();
        assert_eq!(view[0], h.entries[1].id, "pinned first");
        assert_eq!(h.view("hello").len(), 1);
        h.clear();
        assert_eq!(texts(&h), ["pin me"]);
    }

    #[test]
    fn saved_round_trip_is_text_only() {
        let mut h = History::<()>::new(10);
        h.push_text("one".into());
        h.push_image((), 10);
        h.push_text("two".into());
        h.toggle_pin(h.entries[0].id);
        let saved = h.saved();
        assert_eq!(
            saved,
            [
                Saved {
                    text: "two".into(),
                    pinned: true
                },
                Saved {
                    text: "one".into(),
                    pinned: false
                }
            ]
        );
        let mut h2 = History::<()>::new(10);
        h2.load(saved);
        assert_eq!(texts(&h2), ["two", "one"]);
        assert!(h2.entries[0].pinned);
    }

    #[test]
    fn secrets_detected() {
        assert!(is_secret(&[
            "public.utf8-plain-text".into(),
            "org.nspasteboard.ConcealedType".into()
        ]));
        assert!(is_secret(&["x-kde-passwordManagerHint".into()]));
        assert!(!is_secret(&["public.utf8-plain-text".into()]));
    }

    #[test]
    fn previews() {
        assert_eq!(preview("a\n  b\tc"), "a b c");
        assert_eq!(preview(&"x".repeat(400)).chars().count(), PREVIEW_CHARS + 1);
        assert_eq!(meta_text("a\nb\nc"), "3 lines");
    }
}
